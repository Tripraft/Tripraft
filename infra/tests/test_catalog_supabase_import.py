# Purpose: Tests PostgreSQL COPY escaping, supported canonical SQLite DDL conversion and stable export ordering with temporary or in-memory data; no remote database is contacted.
"""Lossless COPY escaping and canonical SQLite-to-PostgreSQL conversion."""
import importlib.util
import sqlite3
from pathlib import Path

import pytest

spec = importlib.util.spec_from_file_location(
    'import_catalog_supabase', Path(__file__).resolve().parents[1]/'tools/import_catalog_supabase.py'
)
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)


def test_copy_preserves_null_empty_unicode_and_control_characters():
    assert module.copy_field(None) == r'\N'
    assert module.copy_field('') == ''
    assert module.copy_field(r'\N') == r'\\N'
    assert module.copy_field('Café\tline\nnext\r\\') == 'Café\\tline\\nnext\\r\\\\'
    assert module.copy_field(b'\x00\xff') == r'\\x00ff'
    with pytest.raises(ValueError, match='NUL'):
        module.copy_field('text\x00value')


def test_converts_canonical_constraints_and_identity_without_dropping_them():
    sql = module.postgres_table('''CREATE TABLE sample (
id INTEGER PRIMARY KEY AUTOINCREMENT,
parent INTEGER REFERENCES sample(id),
hours TEXT CHECK(hours GLOB '[0-2][0-9]:[0-5][0-9]'),
payload BLOB, filters TEXT CHECK(json_valid(filters)),
created_at TEXT DEFAULT (strftime('%Y-%m-%d','now')),
UNIQUE(parent,hours))''')
    assert 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' in sql
    assert 'REFERENCES sample(id)' in sql
    assert "hours ~ '^[0-2][0-9]:[0-5][0-9]$'" in sql
    assert 'payload BYTEA' in sql
    assert 'catalog.sqlite_json_valid(filters)' in sql
    assert 'UNIQUE(parent,hours)' in sql
    assert 'strftime' not in sql


def test_export_retains_primary_key_order_and_original_values(tmp_path):
    with sqlite3.connect(':memory:') as source:
        source.execute('CREATE TABLE sample(id INTEGER PRIMARY KEY,value TEXT,amount REAL)')
        source.executemany('INSERT INTO sample VALUES(?,?,?)', [(2,'',None),(1,'Café\n',1.25)])
        result = module.export_table(source,'sample',tmp_path)
    assert result['rows'] == 2 and result['primary_key'] == ['id']
    assert (tmp_path/'sample.copy').read_text(encoding='utf-8') == '1\tCafé\\n\t1.25\n2\t\t\\N\n'
