# Purpose: Prepares canonical SQLite catalog snapshots, PostgreSQL DDL and COPY exports; explicit apply imports into a new private catalog schema and verifies ordered row hashes before commit.
"""Copy the canonical SQLite catalog into a new, private PostgreSQL catalog schema.

Prepare exports and SQL by default. --apply imports and validates every row in a
single transaction, refusing to replace an existing schema. Credentials remain in
the ignored services/api/.env.supabase file. Application/public tables are untouched.
"""
