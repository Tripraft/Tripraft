FTS_COLUMNS = ['rowid', 'place_name', 'name_english', 'ai_summary', 'place_tip', 'category']
SEARCH_EXPRESSION = "to_tsvector('pg_catalog.english'::regconfig, " + " || ' ' || ".join(
    f"coalesce({name},'')" for name in FTS_COLUMNS[1:]
) + ')'


def file_hash(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def postgres_table(sql):
    # This converter is limited to the validated canonical v2.1 schema.
    sql = re.sub(r'\bINTEGER\s+PRIMARY\s+KEY(?:\s+AUTOINCREMENT)?',
                 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', sql)
    for before, after in [('INTEGER', 'BIGINT'), ('REAL', 'DOUBLE PRECISION'), ('BLOB', 'BYTEA')]:
        sql = re.sub(r'\b' + before + r'\b', after, sql)
    sql = sql.replace("strftime('%Y-%m-%d','now')", "to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD')")
    sql = sql.replace("strftime('%Y-%m-%dT%H:%M:%fZ','now')",
                      "to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"')")
    sql = sql.replace('json_valid(', 'catalog.sqlite_json_valid(')
    sql = re.sub(r"(\w+) GLOB '\[0-2\]\[0-9\]:\[0-5\]\[0-9\]'",
                 r"\1 ~ '^[0-2][0-9]:[0-5][0-9]$'", sql)
    if re.search(r'\b(AUTOINCREMENT|GLOB|strftime)\b', sql):
        raise ValueError('Unhandled SQLite syntax in canonical table definition')
    return sql + ';'


def schema_sql(source, names):
    statements = [
        'CREATE SCHEMA catalog;',
        'REVOKE ALL ON SCHEMA catalog FROM PUBLIC;',
        'SET LOCAL search_path TO catalog, pg_catalog;',
        '''CREATE FUNCTION catalog.sqlite_json_valid(value text) RETURNS boolean
LANGUAGE plpgsql IMMUTABLE STRICT SET search_path=pg_catalog AS $$
BEGIN PERFORM value::json; RETURN true;
EXCEPTION WHEN invalid_text_representation THEN RETURN false;
END; $$;''',
    ]
    for name in names:
        sql = source.execute("SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (name,)).fetchone()[0]
        statements.append(postgres_table(sql))
    for sql, in source.execute("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name"):
        statements.append(sql + ';')
    statements.extend([
        f'CREATE INDEX idx_places_search_postgresql ON catalog.places USING GIN ({SEARCH_EXPRESSION});',
        f'CREATE VIEW catalog.place_search_fts AS SELECT id AS rowid, {", ".join(FTS_COLUMNS[1:])}, '
        f'{SEARCH_EXPRESSION} AS search_vector FROM catalog.places;',
        source.execute("SELECT sql FROM sqlite_master WHERE type='view' AND name='v_top_search_queries'").fetchone()[0] + ';',
        '''CREATE FUNCTION catalog.guard_airport_geography() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,catalog AS $$
BEGIN
 IF NEW.city_id IS NOT NULL AND NOT EXISTS (
  SELECT 1 FROM catalog.cities ci JOIN catalog.states st ON ci.state_id=st.id
  WHERE ci.id=NEW.city_id AND st.country_id=NEW.country_id
    AND (NEW.state_id IS NULL OR st.id=NEW.state_id)
 ) THEN RAISE EXCEPTION 'airport city/state/country mismatch' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER trg_airports_city_guard BEFORE INSERT OR UPDATE OF city_id,state_id,country_id
ON catalog.airports FOR EACH ROW EXECUTE FUNCTION catalog.guard_airport_geography();''',
    ])
    for name in names:
        statements.append(f'ALTER TABLE catalog.{quote(name)} ENABLE ROW LEVEL SECURITY;')
    statements.append('''DO $access$
DECLARE api_role text;
BEGIN
 FOREACH api_role IN ARRAY ARRAY['anon','authenticated','service_role'] LOOP
  IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=api_role) THEN
   EXECUTE format('REVOKE ALL ON SCHEMA catalog FROM %I',api_role);
  END IF;
 END LOOP;
END; $access$;''')
    return '\n\n'.join(statements) + '\n'


def copy_field(value):
    if value is None:
        return r'\N'
    if isinstance(value, bytes):
        value = r'\x' + value.hex()
    elif not isinstance(value, str):
        value = repr(value)
    if '\x00' in value:
        raise ValueError('PostgreSQL text cannot preserve a NUL byte; import stopped without data loss')
    for before, after in [('\\', r'\\'), ('\t', r'\t'), ('\n', r'\n'), ('\r', r'\r'), ('\b', r'\b'), ('\f', r'\f'), ('\v', r'\v')]:
        value = value.replace(before, after)
    return value


def hash_row(digest, row):
    values = [{'bytes_hex': bytes(v).hex()} if isinstance(v, (bytes, memoryview)) else v for v in row]
    digest.update(json.dumps(values, ensure_ascii=False, separators=(',', ':')).encode('utf-8') + b'\n')


def export_table(source, name, directory):
    columns = [r[1] for r in source.execute(f'PRAGMA table_info({quote(name)})')]
    key = [r[1] for r in sorted(source.execute(f'PRAGMA table_info({quote(name)})'), key=lambda r: r[5]) if r[5]]
    if not key:
        raise ValueError(f'No stable primary key: {name}')
    select = ','.join(map(quote, columns))
    order = ','.join(map(quote, key))
    digest, count = hashlib.sha256(), 0
    path = directory / (name + '.copy')
    with path.open('w', encoding='utf-8', newline='') as output:
        for row in source.execute(f'SELECT {select} FROM {quote(name)} ORDER BY {order}'):
            output.write('\t'.join(map(copy_field, row)) + '\n')
            hash_row(digest, row)
            count += 1
    return {'columns': columns, 'primary_key': key, 'rows': count,
            'column_types': {r[1]: r[2] for r in source.execute(f'PRAGMA table_info({quote(name)})')},
            'sha256_rows': digest.hexdigest(), 'export': str(path)}


def verify_rows(raw, name, manifest):
    query = f'SELECT {",".join(map(quote, manifest["columns"]))} FROM catalog.{quote(name)} ORDER BY '
    query += ','.join(quote(key) + (' COLLATE "C"' if manifest.get('column_types', {}).get(key) == 'TEXT' else '')
                      for key in manifest['primary_key'])
    digest, count = hashlib.sha256(), 0
    with raw.cursor(name='verify_' + name) as cursor:
        cursor.itersize = 5000
        cursor.execute(query)
        for row in cursor:
            hash_row(digest, row)
            count += 1
    if count != manifest['rows'] or digest.hexdigest() != manifest['sha256_rows']:
        raise ValueError(f'Row verification failed: {name}; transaction will roll back')
    print(f'Verified {name}: {count} rows', flush=True)


def import_postgres(source, names, manifest, ddl, apply):
    engine = create_engine(database_url(dotenv_values(API/'.env.supabase', interpolate=False)), hide_parameters=True)
    try:
        with closing(engine.raw_connection()) as raw:
            try:
                with raw.cursor() as cursor:
                    cursor.execute("SELECT EXISTS(SELECT 1 FROM pg_namespace WHERE nspname='catalog')")
                    if cursor.fetchone()[0]:
                        raise ValueError('Schema catalog already exists; refusing to overwrite it')
                    cursor.execute('SET LOCAL statement_timeout=0')
                    cursor.execute('SET LOCAL lock_timeout=10000')
                    # Supabase's session default can be 0, which rounds doubles
                    # on SELECT and breaks lossless row verification. Positive
                    # values return exact round-trippable float representations.
                    cursor.execute('SET LOCAL extra_float_digits=3')
                    cursor.execute(ddl)
                    print('PostgreSQL catalog schema validated.', flush=True)
                    if not apply:
                        raw.rollback()
                        return {'schema_preview': 'passed; rolled back'}
                    for name in names:
                        item = manifest[name]
                        with Path(item['export']).open('r', encoding='utf-8', newline='') as data:
                            cursor.copy_expert(
                                f'COPY catalog.{quote(name)} ({",".join(map(quote,item["columns"]))}) '
                                "FROM STDIN WITH (FORMAT text, ENCODING 'UTF8')", data,
                            )
                        print(f'Imported {name}: {item["rows"]} rows', flush=True)
                    source_sequences = dict(source.execute('SELECT name,seq FROM sqlite_sequence'))
                    for name in names:
                        pk = [r for r in source.execute(f'PRAGMA table_info({quote(name)})') if r[5]]
                        if len(pk) == 1 and pk[0][2] == 'INTEGER':
                            col = pk[0][1]
                            maximum = source.execute(f'SELECT max({quote(col)}) FROM {quote(name)}').fetchone()[0]
                            high = max(maximum or 0, source_sequences.get(name, 0))
                            cursor.execute('SELECT setval(pg_get_serial_sequence(%s,%s),%s,%s)',
                                           ('catalog.' + name, col, max(1, high), high > 0))
                for name in names:
                    verify_rows(raw, name, manifest[name])
                fts = {'columns': FTS_COLUMNS, 'primary_key': ['rowid'], 'rows': manifest['places']['rows']}
                digest = hashlib.sha256()
                for row in source.execute('SELECT ' + ','.join(FTS_COLUMNS) + ' FROM place_search_fts ORDER BY rowid'):
                    hash_row(digest, row)
                fts['sha256_rows'] = digest.hexdigest()
                verify_rows(raw, 'place_search_fts', fts)
                with raw.cursor() as cursor:
                    cursor.execute("SELECT count(*) FROM catalog.place_search_fts WHERE search_vector @@ plainto_tsquery('english','museum')")
                    search_matches = cursor.fetchone()[0]
                    if not search_matches:
                        raise ValueError('PostgreSQL full-text search smoke check failed')
                    cursor.execute('SELECT pg_database_size(current_database()),pg_total_relation_size(\'catalog.places\')')
                    sizes = cursor.fetchone()
                raw.commit()
                return {'applied': True, 'full_text_museum_matches': search_matches,
                        'database_bytes': sizes[0], 'places_total_bytes': sizes[1],
                        'all_rows_verified': True, 'foreign_keys_and_checks': 'enforced during COPY'}
            except BaseException:
                raw.rollback()
                raise
    finally:
        engine.dispose()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT/'data/catalog/tripraft-canonical.db')
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--check-schema', action='store_true', help='Create/roll back PostgreSQL DDL only; no rows imported.')
    parser.add_argument('--prepared', type=Path, help='Reuse an existing prepared report and its immutable snapshot.')
    args = parser.parse_args()
    if args.apply and args.check_schema:
        raise ValueError('Choose --apply or --check-schema')
    if args.prepared:
        report_path = args.prepared.resolve()
        report = json.loads(report_path.read_text(encoding='utf-8'))
        work = report_path.parent
    else:
        work = ROOT/'.tripraft/catalog-supabase'/datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
        work.mkdir(parents=True)
        report_path = work/'report.json'
        snapshot = work/'source-snapshot.db'
        with closing(sqlite3.connect(args.source.resolve().as_uri()+'?mode=ro', uri=True)) as original:
            with closing(sqlite3.connect(snapshot)) as saved:
                original.backup(saved)
        report = {'source': str(args.source.resolve()), 'source_sha256_before': file_hash(args.source),
                  'snapshot': str(snapshot), 'snapshot_sha256': file_hash(snapshot), 'applied': False}
    snapshot = Path(report['snapshot'])
    if file_hash(snapshot) != report['snapshot_sha256']:
        raise ValueError('Prepared snapshot hash changed')
    with closing(sqlite3.connect(snapshot.resolve().as_uri()+'?mode=ro', uri=True)) as source:
        counts = validate_database(snapshot)
        names = tables(source)
        ddl = schema_sql(source, names)
        (work/'schema-postgresql.sql').write_text(ddl, encoding='utf-8')
        if not args.prepared:
            report['tables'] = {name: export_table(source, name, work) for name in names}
            report['source_counts'] = counts
        for name in names:
            report['tables'][name]['column_types'] = {
                r[1]: r[2] for r in source.execute(f'PRAGMA table_info({quote(name)})')
            }
        report['target_schema'] = 'catalog'
        report_path.write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
        if args.apply or args.check_schema:
            report.update(import_postgres(source, names, report['tables'], ddl, args.apply))
    report['source_unchanged'] = file_hash(Path(report['source'])) == report['source_sha256_before']
    report_path.write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
    print(f'Report: {report_path}', flush=True)
    print('Imported catalog successfully.' if report.get('applied') else 'Prepared catalog; source remains unchanged.', flush=True)


if __name__ == '__main__':
    try:
        main()
    except psycopg2.Error as error:
        print(database_error_message(SimpleNamespace(orig=error)), file=sys.stderr)
        raise SystemExit(1) from None
    except SQLAlchemyError as error:
        print(database_error_message(error), file=sys.stderr)
        raise SystemExit(1) from None
    except ValueError as error:
        print(str(error), file=sys.stderr)
        raise SystemExit(1) from None
